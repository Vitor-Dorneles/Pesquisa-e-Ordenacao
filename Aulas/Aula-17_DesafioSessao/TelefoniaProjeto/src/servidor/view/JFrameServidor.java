    private void jButtonCarregarArquivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCarregarArquivoActionPerformed
        String caminho = jTextFieldNomeArquivo.getText().trim();

        if (caminho.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Você precisa informar o caminho e nome do arquivo da base");
            return;
        }

        try {
            int quantidade = controller.carregarArquivo(caminho);
            jTextAreaDadosSessoes.setText(controller.listarSessoes());
            txtCelularBuscado.setEnabled(true);
            btnBuscarSessao.setEnabled(true);
            txtCelularBuscado.requestFocusInWindow();
            jTextAreaDadosSessoes.setCaretPosition(0);
            JOptionPane.showMessageDialog(this, quantidade + " sessões carregadas.");
        } catch (NoSuchFileException e) {
            jTextAreaDadosSessoes.setText("");
            txtCelularBuscado.setEnabled(false);
            btnBuscarSessao.setEnabled(false);
            txAResultadoBusca.setText("");
            JOptionPane.showMessageDialog(this, "Arquivo não localizado: " + caminho,
                    "Erro", JOptionPane.ERROR_MESSAGE);
        } catch (IOException e) {
            jTextAreaDadosSessoes.setText("");
            txtCelularBuscado.setEnabled(false);
            btnBuscarSessao.setEnabled(false);
            txAResultadoBusca.setText("");
            JOptionPane.showMessageDialog(this, "Arquivo com problemas: " + e.getMessage(),
                    "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonCarregarArquivoActionPerformed

    private void btnProcurarArquivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcurarArquivoActionPerformed
        JFileChooser seletor = new JFileChooser(new java.io.File(".")); //abre onde o programa roda
        seletor.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Arquivos de texto", "txt"));

        if (seletor.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            jTextFieldNomeArquivo.setText(seletor.getSelectedFile().getPath());
        }
    }//GEN-LAST:event_btnProcurarArquivoActionPerformed

    private void btnBuscarSessaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarSessaoActionPerformed
        String celular = txtCelularBuscado.getText().trim();

        if (celular.isEmpty()) {
            return;
        }

        Optional<Sessao> encontrada = controller.buscarSessao(celular);

        if (encontrada.isPresent()) {
            Sessao sessao = encontrada.get();
            txAResultadoBusca.setText("Celular: " + sessao.getNumeroCelular() + "\n" + sessao.getDadosSessao());
        } else {
            txAResultadoBusca.setText("Nenhuma sessao para o número: " + celular);
        }
    }//GEN-LAST:event_btnBuscarSessaoActionPerformed

